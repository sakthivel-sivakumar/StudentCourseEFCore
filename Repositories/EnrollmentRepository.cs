using Microsoft.EntityFrameworkCore;
using StudentCourseEFCore.Data;
using StudentCourseEFCore.Models;

namespace StudentCourseEFCore.Repositories;

public class EnrollmentRepository
{
    private readonly AppDbContext db;

    public EnrollmentRepository(AppDbContext context)
    {
        db = context;
    }


    public async Task<int> AddAsync(Enrollment enrollment)
    {
        // Verify that the student exists.
        bool studentExists = await db.Students
            .AnyAsync(s => s.StudentId == enrollment.StudentId);

        if (!studentExists)
        {
            throw new InvalidOperationException(
                "The selected student does not exist.");
        }

        // Verify that the course exists.
        bool courseExists = await db.Courses
            .AnyAsync(c => c.CourseId == enrollment.CourseId);

        if (!courseExists)
        {
            throw new InvalidOperationException(
                "The selected course does not exist.");
        }

        // Repeated enrollments are allowed.
        db.Enrollments.Add(enrollment);

        await db.SaveChangesAsync();

        // EnrollmentId is generated by the database.
        return enrollment.EnrollmentId;
    }

    public async Task<List<Enrollment>> GetAllAsync()
    {
        return await db.Enrollments
            .AsNoTracking()
            .Include(e => e.Student)
            .Include(e => e.Course)
            .OrderBy(e => e.EnrollmentId)
            .ToListAsync();
    }

    public async Task<Enrollment?> GetByIdAsync(int enrollmentId)
    {
        return await db.Enrollments
            .AsNoTracking()
            .Include(e => e.Student)
            .Include(e => e.Course)
            .FirstOrDefaultAsync(
                e => e.EnrollmentId == enrollmentId);
    }

    public async Task<List<Enrollment>> GetByStudentIdAsync(int studentId)
    {
        return await db.Enrollments
            .AsNoTracking()
            .Include(e => e.Student)
            .Include(e => e.Course)
            .Where(e => e.StudentId == studentId)
            .OrderBy(e => e.EnrollmentId)
            .ToListAsync();
    }

    public async Task<bool> DeleteAsync(int enrollmentId)
    {
        var enrollment = await db.Enrollments
            .FindAsync(enrollmentId);

        if (enrollment is null)
        {
            return false;
        }

        db.Enrollments.Remove(enrollment);

        await db.SaveChangesAsync();

        return true;
    }
}